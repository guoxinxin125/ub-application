/* Disposable, trusted two-guest ABI. No arbitrary executable payloads. */
#define RA_ABI 3
#define RA_CACHE_WB 0
#define RA_CACHE_UC 1
/* Linux x86 PAT slot 3 must be UC; verified against IA32_PAT by A. */
#define RA_UC_BITS 0x18ULL
#define RA_PROBE_OFFSET 128
#define RA_QUERY_OFFSET 512
/* Read-only records in the existing single heap page. No new page footprint. */
#define RA_RECORD_OFFSET 64
#define RA_RECORD_STRIDE 64
#define RA_RECORD_COUNT 32
#define RA_MAGIC 0x52414c5250433031ULL
#define RA_BYTES 0x100000
#define RA_KERNEL 0x1000
#define RA_TABLE(d, l) (0x10000 + (d) * 0x5000 + (l) * 0x1000)
#define RA_HEAP 0x30000
#define RA_CODE_IMAGE(d) (0x40000 + (d) * 0x1000)
#define RA_CONTEXT(d) (0x50000 + (d) * 0x1000)
#define RA_VA 0x100000000ULL
#define RA_STACK (RA_VA + 0x2000)
#define RA_DATA (RA_VA + 0x4000)
#define RA_ARGS (RA_VA + 0x6000)
#define RA_DOMAINS 3
#define RA_DIRECT 0
#define RA_MIDDLE 1
#define RA_LEAF 2

struct ra_publication {
	__u64 magic, request, complete, bar_gpa;
	__u64 code_gpa[3], stack_gpa[3], args_gpa[3];
	__u32 abi, levels;
	__u64 b_initializations, b_executions;
	__u32 cache_mode, reserved;
};
struct ra_initial_context {
	__u64 gpr[15], ip, cs, flags, sp, ss;
};
struct ra_call {
	__u64 a, b, result;
	__u64 enter_ns, dispatch_ns, return_ns, resume_ns;
	__u32 procedure, transitions, cpu, fault_vector;
};
#define RA_PREPARE _IO('R', 0x70)
#define RA_CALL _IOW('R', 0x71, struct ra_call)
#define RA_REPORT _IOR('R', 0x72, struct ra_call)
struct ra_probe {
	__u64 empty, warm, cold, warm_value, cold_value;
	__u32 cache_mode, abi;
};
#define RA_PROBE _IO('R', 0x73)
#define RA_PROBE_REPORT _IOR('R', 0x74, struct ra_probe)
struct ra_detail {
	__u64 stamp[12];
	__u32 switches, noflush, flush, reserved;
};
#define RA_DIAG_CALL _IOW('R', 0x75, struct ra_call)
#define RA_DETAIL_REPORT _IOR('R', 0x76, struct ra_detail)
/* Experiment-only: force the next entry into each domain to omit NOFLUSH.
 * Does not evict page-table bytes from data caches or flush host EPT. */
#define RA_RESET_TRANSLATIONS _IO('R', 0x77)
/* Prepare the connection without diagnostic root/heap timing probes.  This
 * retains publication validation, page-table verification, code copying and
 * context setup, so it models the first business use after required setup. */
#define RA_PREPARE_FIRST_USE _IO('R', 0x78)

